/**
 * Regions covered by platform UI (captions, buttons, progress bars), as
 * fractions of the frame. Deliberately conservative.
 */
export const SAFE_AREA_PRESETS: Record<Exclude<SafeAreaPreset, 'custom'>, Omit<SafeArea, 'preset'> & { label: string }> = {
  none: { label: 'None', top: 0, bottom: 0, left: 0, right: 0 },
  universal: { label: 'All social platforms', top: 0.1, bottom: 0.14, left: 0.06, right: 0.12 },
  tiktok: { label: 'TikTok', top: 0.09, bottom: 0.14, left: 0.05, right: 0.13 },
  reels: { label: 'Instagram Reels', top: 0.1, bottom: 0.14, left: 0.05, right: 0.12 },
  shorts: { label: 'YouTube Shorts', top: 0.08, bottom: 0.13, left: 0.05, right: 0.12 },
}

export function safeAreaFromPreset(preset: Exclude<SafeAreaPreset, 'custom'>): SafeArea {
  const { top, bottom, left, right } = SAFE_AREA_PRESETS[preset]
  return { preset, top, bottom, left, right }
}

export function createProject(name: string, now: Date = new Date()): Project {
  const trackId = createId('track')
  const ts = now.toISOString()
  return {
    format: 'cfproject',
    schemaVersion: CURRENT_SCHEMA_VERSION,
    id: createId('proj'),
    name,
    createdAt: ts,
    updatedAt: ts,
    composition: { width: 1080, height: 1920, fps: 30 },
    media: [],
    primaryVideoId: null,
    captionTracks: [{ id: trackId, name: 'Captions', language: 'und', cues: [] }],
    activeCaptionTrackId: trackId,
    captionStyle: { styleId: 'bold-pop', templateId: null, config: structuredClone(BOLD_POP_DEFAULTS) },
    captionLayer: { keyframes: [] },
    speakers: [],
    safeArea: safeAreaFromPreset('universal'),
    audioTracks: [],
  }
}
